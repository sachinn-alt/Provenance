// Interactive Sandbox Export: SQLite DDL & Insert Script
// ----------------------------------------------------
export function exportToSQLiteSQL(records: ExtractedRecord[], schema: GeneratedSchema): string {
  const tableName = schema.entityName.replace(/[^a-zA-Z0-9_]/g, '').toLowerCase() || 'records';
  
  const typeMap: Record<string, string> = {
    string: 'TEXT',
    number: 'REAL',
    currency: 'TEXT',
    url: 'TEXT',
    date: 'TEXT',
    badge: 'TEXT'
  };

  const colDefs = schema.attributes.map(attr => {
    const colName = attr.name.replace(/[^a-zA-Z0-9_]/g, '_');
    const colType = typeMap[attr.type] || 'TEXT';
    return `    ${colName} ${colType}${attr.required ? ' NOT NULL' : ''}`;
  });

  const columnsList = ['record_id', ...schema.attributes.map(a => a.name.replace(/[^a-zA-Z0-9_]/g, '_')), 'validation_score', 'is_duplicate'].join(', ');

  const insertStatements = records.map(r => {
    const vals = [
      `'${r.id}'`,
      ...schema.attributes.map(a => {
        const v = r.data[a.name];
        if (v === undefined || v === null) return 'NULL';
        return `'${String(v).replace(/'/g, "''")}'`;
      }),
      r.validationScore,
      r.isDuplicate ? 1 : 0
    ];
    return `INSERT INTO ${tableName} (${columnsList}) VALUES (${vals.join(', ')});`;
  });

  return `-- =======================================================
-- Provenance — SQLite DDL & Insert Script
-- Table: ${tableName} (${records.length} rows)
-- =======================================================

DROP TABLE IF EXISTS ${tableName};

CREATE TABLE ${tableName} (
    record_id TEXT PRIMARY KEY,
${colDefs.join(',\n')},
    validation_score INTEGER,
    is_duplicate INTEGER
);

-- Verified Entity Inserts:
${insertStatements.join('\n')}

SELECT COUNT(*) AS total_verified_rows FROM ${tableName};
`;
}
